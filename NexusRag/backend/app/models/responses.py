"""API response models for NexusRAG (Phase 11).

Defines external HTTP response contracts using Pydantic v2.
Decouples internal domain dataclasses from public API representations.
"""

from typing import Any, List
from pydantic import BaseModel, Field


class SourceResponse(BaseModel):
    """Citation metadata for a single source document page."""

    source: str = Field(..., description="Filename of the source document")
    file_type: str = Field(default="", description="Extension / format of the document")
    page: int = Field(default=1, description="1-indexed page number from the original file")


class ChatResponse(BaseModel):
    """Complete grounded answer response from the RAG pipeline."""

    answer: str = Field(
        ...,
        description="Grounded answer text generated by the LLM, or controlled no-context message",
    )
    sources: List[SourceResponse] = Field(
        default_factory=list,
        description="Deduplicated list of citations preserving page numbers",
    )
    query: str = Field(..., description="The user question, preserved verbatim")
    model: str = Field(default="", description="LLM model identifier used for generation")
    context_chunks_used: int = Field(
        default=0, description="Number of context chunks supplied to the LLM"
    )

    @classmethod
    def from_rag_response(cls, rag_response: Any) -> "ChatResponse":
        """Converts internal RAGResponse dataclass into a Pydantic API response."""
        sources = [
            SourceResponse(
                source=getattr(s, "source", "unknown"),
                file_type=getattr(s, "file_type", ""),
                page=getattr(s, "page", 1),
            )
            for s in getattr(rag_response, "sources", [])
        ]
        return cls(
            answer=getattr(rag_response, "answer", ""),
            sources=sources,
            query=getattr(rag_response, "query", ""),
            model=getattr(rag_response, "model", ""),
            context_chunks_used=getattr(rag_response, "context_chunks_used", 0),
        )


class DocumentUploadResponse(BaseModel):
    """Result of document upload, parsing, chunking, and indexing."""

    filename: str = Field(..., description="Sanitized original filename")
    file_type: str = Field(..., description="Detected file extension")
    file_size_bytes: int = Field(..., description="Total size of the file in bytes")
    chunks_created: int = Field(..., description="Number of text chunks created and indexed")
    status: str = Field(default="success", description="Ingestion status string ('success')")
    message: str = Field(..., description="Human-readable result summary")


class HealthResponse(BaseModel):
    """Liveness probe response model."""

    status: str = Field(default="healthy", description="Application liveness status")
